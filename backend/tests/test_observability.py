class TestCorrelationId:
    """Tests for the X-Correlation-ID request/response middleware."""

    def test_response_contains_correlation_id_header(self, client):
        """Every response must include an X-Correlation-ID header."""
        resp = client.get("/api/health")
        assert "X-Correlation-ID" in resp.headers

    def test_generated_correlation_id_is_valid_uuid(self, client):
        """When the caller does not supply a correlation ID, the server
        must generate a valid UUID4."""
        resp = client.get("/api/health")
        cid = resp.headers.get("X-Correlation-ID")
        assert cid is not None
        # Must parse as a UUID without raising ValueError.
        parsed = uuid.UUID(cid)
        assert str(parsed) == cid

    def test_caller_supplied_correlation_id_is_echoed(self, client):
        """When the caller supplies X-Correlation-ID, it must be echoed
        back in the response header unchanged."""
        supplied_id = "test-corr-id-12345"
        resp = client.get(
            "/api/health",
            headers={"X-Correlation-ID": supplied_id},
        )
        assert resp.headers.get("X-Correlation-ID") == supplied_id

    def test_different_requests_get_different_ids(self, client):
        """Two requests without a supplied ID should receive distinct UUIDs."""
        r1 = client.get("/api/health")
        r2 = client.get("/api/health")
        id1 = r1.headers.get("X-Correlation-ID")
        id2 = r2.headers.get("X-Correlation-ID")
        assert id1 != id2

    def test_correlation_id_present_on_404(self, client):
        """Correlation ID should be present even on error responses."""
        resp = client.get("/api/this-route-does-not-exist-8h")
        assert "X-Correlation-ID" in resp.headers

    def test_correlation_id_present_on_post(self, client):
        """Correlation ID should be present on POST responses."""
        resp = client.post(
            "/api/auth/artist/login",
            json={"email": "notexist@example.com", "password": "pw"},
        )
        assert "X-Correlation-ID" in resp.headers


