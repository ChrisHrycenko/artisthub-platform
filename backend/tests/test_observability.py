class TestStructuredLogging:
    """Tests for the JSON logging formatter."""

    def test_json_formatter_produces_valid_json(self):
        """_JSONFormatter must produce a parseable JSON string."""
        import logging
        from io import StringIO
        from app.utils.structured_logging import _JSONFormatter

        formatter = _JSONFormatter(worker="test-worker")
        record = logging.LogRecord(
            name="test.logger",
            level=logging.INFO,
            pathname="",
            lineno=0,
            msg="Hello %s",
            args=("world",),
            exc_info=None,
        )
        output = formatter.format(record)
        parsed = json.loads(output)

        assert parsed["level"] == "INFO"
        assert parsed["logger"] == "test.logger"
        assert parsed["message"] == "Hello world"
        assert parsed["worker"] == "test-worker"
        assert "timestamp" in parsed
        # Timestamp must end with Z (UTC).
        assert parsed["timestamp"].endswith("Z")

    def test_json_formatter_includes_correlation_id(self):
        """correlation_id injected via extra= must appear in the JSON output."""
        import logging
        from app.utils.structured_logging import _JSONFormatter

        formatter = _JSONFormatter()
        record = logging.LogRecord(
            name="test",
            level=logging.WARNING,
            pathname="",
            lineno=0,
            msg="test message",
            args=(),
            exc_info=None,
        )
        record.correlation_id = "abc-123"
        output = formatter.format(record)
        parsed = json.loads(output)
        assert parsed["correlation_id"] == "abc-123"

    def test_configure_structured_logging_sets_json_formatter(self):
        """configure_structured_logging() must attach a JSON formatter to the
        root logger without raising an exception."""
        import logging
        from io import StringIO
        from app.utils.structured_logging import configure_structured_logging

        stream = StringIO()
        configure_structured_logging(level="DEBUG", worker="relay", stream=stream)

        root = logging.getLogger()
        assert len(root.handlers) >= 1
        assert isinstance(root.handlers[0].formatter, type(root.handlers[0].formatter))

        # Emit a test log line and verify it is valid JSON.
        test_logger = logging.getLogger("test.structured")
        test_logger.info("structured log test")
        output = stream.getvalue().strip()
        if output:
            parsed = json.loads(output.splitlines()[-1])
            assert parsed["worker"] == "relay"


