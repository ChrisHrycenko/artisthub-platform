class TestWorkerMetricsHelpers:
    """Tests for safe_inc and safe_set no-op behaviour on None."""

    def test_safe_inc_on_none_does_not_raise(self):
        """safe_inc(None) must silently do nothing."""
        from app.utils.worker_metrics import safe_inc
        safe_inc(None)  # must not raise

    def test_safe_set_on_none_does_not_raise(self):
        """safe_set(None, value) must silently do nothing."""
        from app.utils.worker_metrics import safe_set
        safe_set(None, 42.0)  # must not raise

    def test_safe_inc_on_counter_increments(self):
        """safe_inc on a real Counter must increment it."""
        from prometheus_client import Counter, CollectorRegistry
        from app.utils.worker_metrics import safe_inc

        reg = CollectorRegistry()
        counter = Counter(
            "test_safe_inc_total",
            "Test counter",
            registry=reg,
        )
        safe_inc(counter)
        assert reg.get_sample_value("test_safe_inc_total") == 1.0

    def test_safe_set_on_gauge_sets_value(self):
        """safe_set on a real Gauge must set the value."""
        from prometheus_client import Gauge, CollectorRegistry
        from app.utils.worker_metrics import safe_set

        reg = CollectorRegistry()
        gauge = Gauge(
            "test_safe_set_gauge",
            "Test gauge",
            registry=reg,
        )
        safe_set(gauge, 99.5)
        assert reg.get_sample_value("test_safe_set_gauge") == 99.5

    def test_safe_inc_with_labels(self):
        """safe_inc on a labeled Counter must increment the correct label."""
        from prometheus_client import Counter, CollectorRegistry
        from app.utils.worker_metrics import safe_inc

        reg = CollectorRegistry()
        counter = Counter(
            "test_safe_inc_labeled_total",
            "Labeled test counter",
            ["topic"],
            registry=reg,
        )
        safe_inc(counter, labels={"topic": "artisthub.social"})
        assert reg.get_sample_value(
            "test_safe_inc_labeled_total",
            labels={"topic": "artisthub.social"},
        ) == 1.0

    def test_start_metrics_server_unknown_worker(self):
        """start_metrics_server with an unknown worker name must return an
        empty metrics dict without raising."""
        from app.utils.worker_metrics import start_metrics_server

        # Port 0 lets the OS assign an ephemeral port; we immediately
        # check the return value, not the actual HTTP server.
        # Note: start_http_server is called inside; if it fails we still
        # don't want an exception to bubble up.
        registry, metrics = start_metrics_server("unknown_worker_xyz", port=19191)
        # metrics is empty for unknown workers.
        assert isinstance(metrics, dict)
        assert len(metrics) == 0
